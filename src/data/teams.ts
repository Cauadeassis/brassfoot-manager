import NATIONALITIES_DATA from "./nationalities";
import type { Nationality } from "./nationalities";
interface CreateTeamProps {
  id: number;
  key: string;
  name: string;
  shield: string;
  division: Division;
  overall: number;
  money: number;
  type: TeamType;
  nationality: Nationality;
}

const createTeam = (baseData: CreateTeamProps): Team => {
  const region = NATIONALITIES_DATA[baseData.nationality as Nationality]
    ?.region as Region;
  const defaultTemplates = COMPETITION_TEMPLATES[baseData.type]?.[region] || {};
  const specificDescriptions = TEAM_DESCRIPTIONS[baseData.key] || {};
  return {
    id: baseData.id,
    key: baseData.key,
    name: baseData.name,
    shield: baseData.shield,
    division: baseData.division,
    overall: baseData.overall,
    money: baseData.money,
    type: baseData.type,
    nationality: baseData.nationality,
    competitionDescriptions: {
      ...defaultTemplates,
      ...specificDescriptions,
    },
    statistics: {
      points: 0,
      wins: 0,
      draws: 0,
      losses: 0,
      goalsFor: 0,
      goalsAgainst: 0,
      matchesPlayed: 0,
    },
    squad: [],
    startersId: [],
    tactics: {
      formation: "4-3-3",
      style: "balanced",
      captainId: null,
      takers: {
        penalty: null,
        freeKick: null,
        corner: null,
      },
    },
  };
};

